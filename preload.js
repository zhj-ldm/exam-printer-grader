const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  discover: () => ipcRenderer.invoke('discover'),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  scanPage: host => ipcRenderer.invoke('scan-page', host),
  split: imagePath => ipcRenderer.invoke('split', imagePath),
  gradeOne: payload => ipcRenderer.invoke('grade-one', payload),
  renderMarks: payload => ipcRenderer.invoke('render-marks', payload),
  historyList: () => ipcRenderer.invoke('history-list'),
  historyDelete: id => ipcRenderer.invoke('history-delete', id),
  storageInfo: () => ipcRenderer.invoke('storage-info'),
  storageChoose: () => ipcRenderer.invoke('storage-choose'),
  storageOpen: () => ipcRenderer.invoke('storage-open'),
  cleanupTemp: () => ipcRenderer.invoke('cleanup-temp'),
  renderDebug: payload => ipcRenderer.invoke('render-debug', payload),
  cropBlock: payload => ipcRenderer.invoke('crop-block', payload),
  auto: payload => ipcRenderer.invoke('auto', payload),
  openFile: p => ipcRenderer.invoke('open-file', p),
  print: p => ipcRenderer.invoke('print', p),
  onStage: cb => ipcRenderer.on('stage', (_e, s) => cb(s)),
  getConfig: () => ipcRenderer.invoke('config-get'),
  setConfig: patch => ipcRenderer.invoke('config-set', patch),
  scannerStatus: host => ipcRenderer.invoke('scanner-status', host),
  testModel: payload => ipcRenderer.invoke('model-test', payload),
  printerInfo: () => ipcRenderer.invoke('printer-info'),
  clearQueue: () => ipcRenderer.invoke('clear-queue'),
  testPrint: () => ipcRenderer.invoke('test-print'),
});
